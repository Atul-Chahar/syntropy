/** The cuisine a user eats most, from their profile: it orders lists, never hides foods. */
export type CuisinePref = 'indian' | 'global' | 'both'

/** Everyday foods for someone who mostly eats non-Indian food. */
export const FREQUENT_GLOBAL_IDS = [
  'scrambled-eggs',
  'toast',
  'oatmeal',
  'greek-yogurt-plain',
  'banana',
  'grilled-chicken',
  'white-rice-cup',
  'pasta',
  'salmon',
  'apple',
  'almonds',
  'whey',
]

/** Quick add "Frequent" defaults for a cuisine preference; "both" interleaves the two lists. */
export function frequentIds(pref: CuisinePref = 'indian'): string[] {
  if (pref === 'indian') return FREQUENT_IDS
  if (pref === 'global') return FREQUENT_GLOBAL_IDS
  const out: string[] = []
  for (let i = 0; i < Math.max(FREQUENT_IDS.length, FREQUENT_GLOBAL_IDS.length); i++)
    for (const id of [FREQUENT_IDS[i], FREQUENT_GLOBAL_IDS[i]])
      if (id && !out.includes(id)) out.push(id)
  return out.slice(0, 16)
}

/** Stable re-order that lists the preferred cuisine first ("both" keeps the order). */
export function byCuisine<T extends { cuisine: Food['cuisine'] }>(
  foods: T[],
  pref: CuisinePref,
): T[] {
  if (pref === 'both') return foods
  return [...foods].sort((a, b) => Number(b.cuisine === pref) - Number(a.cuisine === pref))
}

/** "2 pc", "1 katori", "½ katori", "1.5 glass". */
export function formatQty(qty: number, unit: Unit): string {
  const n = qty === 0.5 ? '½' : Number.isInteger(qty) ? String(qty) : qty.toFixed(1)
  if (unit === 'serving') return qty === 1 ? '1 serving' : `${n} servings`
  if (unit === 'g' || unit === 'ml') return `${Math.round(qty)} ${unit}`
  return `${n} ${unit}`
}
