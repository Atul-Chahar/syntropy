/*
 * Indian (and a few everyday global) foods with values per ONE serving unit.
 *
 * Every value is an ESTIMATE. The numbers were compiled for Syntropy from public references
 * — the ICMR–NIN Indian Food Composition Tables (IFCT 2017) for ingredients and published
 * recipe-level values such as the Indian Nutrient Databank (INDB) — then rounded to typical
 * home portions. Home recipes vary by ±25 % (mostly oil and ghee), which is why every AI or
 * table estimate is shown to the user to confirm or adjust before it is saved.
 *
 * Units: pc (piece), katori (150 g bowl), cup (150 ml), glass (250 ml), plate, bowl,
 * serving (stated grams), tbsp, scoop.
 */

export type Unit =
  | 'pc'
  | 'katori'
  | 'cup'
  | 'glass'
  | 'plate'
  | 'bowl'
  | 'serving'
  | 'tbsp'
  | 'scoop'
  | 'g'
  | 'ml'

export type FoodCategory =
  | 'bread'
  | 'rice'
  | 'dal'
  | 'sabzi'
  | 'nonveg'
  | 'egg'
  | 'south'
  | 'snack'
  | 'sweet'
  | 'dairy'
  | 'drink'
  | 'fruit'
  | 'breakfast'
  | 'protein'
  | 'chinese'

