/*
 * Indian and global foods with values per ONE serving unit.
 *
 * Every value is an ESTIMATE. Indian rows are sourced in ../data/foods-sourced.json (with the recipe,
 * portion maths and a confidence rating) from the Indian Nutrient Databank (INDB) recipes, the
 * ICMR–NIN Indian Food Composition Tables (IFCT 2017) and USDA FoodData Central; see
 * ../data/SOURCES.md. The global rows (fast food, Western, East Asian and Middle Eastern dishes,
 * meats, fruit and veg, packaged snacks, drinks) come straight from USDA FoodData Central (FNDDS and
 * SR Legacy) with the FDC id per row in ../data/foods-global-sourced.json. Indian values are home-style; restaurant versions often carry 1.3–1.8x the oil. Home recipes vary by ±25 % (mostly oil and ghee), which is why every AI or
 * table estimate is shown to the user to confirm or adjust before it is saved.
 *
 * Units: pc (piece), katori (150 g bowl), cup (150 ml), glass (250 ml), plate, bowl,
 * serving (stated grams), tbsp, scoop.
 */

export type Unit =
  | 'pc'
  | 'katori'
  | 'cup'
  | 'glass'
  | 'plate'
  | 'bowl'
  | 'serving'
  | 'tbsp'
  | 'scoop'
  | 'g'
  | 'ml'

